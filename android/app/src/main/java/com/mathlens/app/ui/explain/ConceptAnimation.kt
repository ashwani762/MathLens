/** Splits "lhs = rhs" (top level) for the balance scene. */
private fun splitEquation(latex: String): Pair<String, String>? {
    val parts = latex.split(" = ")
    if (parts.size != 2 || latex.contains("\\quad") || latex.contains("\\begin")) return null
    return parts[0].trim() to parts[1].trim()
}

