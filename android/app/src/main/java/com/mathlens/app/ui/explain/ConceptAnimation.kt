private fun fractionOf(latex: String): Pair<Int, Int>? {
    val m = Regex("^\\\\frac\\{(\\d+)\\}\\{(\\d+)\\}$").find(latex.trim()) ?: return null
    val p = m.groupValues[1].toIntOrNull() ?: return null
    val q = m.groupValues[2].toIntOrNull() ?: return null
    return if (q in 2..12 && p in 1..(3 * q)) p to q else null
}

// ------------------------------------------------------------------ factorial: arrangements

@Composable
private fun FactorialScene(s: Solution, modifier: Modifier) {
    val n = Regex("(\\d+)!").find(s.input)?.groupValues?.get(1)?.toIntOrNull()
    if (n == null || n < 1 || n > 6) {
        Box(modifier) { PaperArt(Modifier.fillMaxSize(), seed = s.query.hashCode(), background = Tone.Ivory) }
        return
    }
    val perms = remember(n) { permutations((0 until n).toList()) }
    val t = loopTime(12f)
    val shown = ((t / 12f) * perms.size).toInt().coerceIn(0, perms.size - 1)
    val colors = listOf(Tone.Terracotta, Tone.Ochre, Tone.Sage, Tone.Klein, Tone.Ink, Tone.Blush)
    SceneLayout("Arrangement ${shown + 1} of ${perms.size}", modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val r = min(size.width / (n * 3f), size.height * 0.16f)
            val order = perms[shown]
            val prev = perms[(shown - 1).coerceAtLeast(0)]
            val frac = ((t / 12f) * perms.size) - shown
            val e = frac.coerceIn(0f, 1f).let { it * it * (3 - 2 * it) }
            for (token in 0 until n) {
                val from = prev.indexOf(token); val to = order.indexOf(token)
                val pos = from + (to - from) * min(1f, e * 2.5f)
                val x = size.width / 2 + (pos - (n - 1) / 2f) * r * 2.6f
                val arc = if (from != to) -r * 1.4f * kotlin.math.sin(Math.PI * min(1f, e * 2.5f)).toFloat() else 0f
                drawCircle(colors[token], r, Offset(x, size.height * 0.5f + arc))
            }
        }
    }
}

private fun <T> permutations(items: List<T>): List<List<T>> =
    if (items.size <= 1) listOf(items) else items.flatMap { head -> permutations(items - head).map { listOf(head) + it } }

