/** Looping time in seconds. */
/**
 * Scene clock. Scenes are written in "scene seconds"; real time runs [TEMPO] times slower so every
 * caption has time to be read. Captions and drawings read the same clock, so they stay in sync.
 */
const val TEMPO = 1.9f

@Composable
fun loopTime(periodSec: Float): Float {
    val t = rememberInfiniteTransition(label = "loop")
    val v by t.animateFloat(0f, periodSec, infiniteRepeatable(tween((periodSec * 1000 * TEMPO).toInt(), easing = LinearEasing), RepeatMode.Restart), label = "loopT")
    return v
}

private fun phase(t: Float, start: Float, dur: Float): Float = ((t - start) / dur).coerceIn(0f, 1f).let { it * it * (3 - 2 * it) }

private class Frame(val xmin: Double, val xmax: Double, val ymin: Double, val ymax: Double, val w: Float, val h: Float) {
    fun sx(x: Double) = ((x - xmin) / (xmax - xmin) * w).toFloat()
    fun sy(y: Double) = ((ymax - y) / (ymax - ymin) * h).toFloat()
    fun wx(px: Float) = xmin + px / w * (xmax - xmin)
}

private fun frameFor(spec: PlotSpec, w: Float, h: Float, equal: Boolean = false): Frame {
    var (x0, x1, y0, y1) = spec.view.toList()
    if (equal) {
        val ux = (x1 - x0) / w; val uy = (y1 - y0) / h; val u = max(ux, uy)
        val cx = (x0 + x1) / 2; val cy = (y0 + y1) / 2
        x0 = cx - u * w / 2; x1 = cx + u * w / 2; y0 = cy - u * h / 2; y1 = cy + u * h / 2
    }
    return Frame(x0, x1, y0, y1, w, h)
}

private fun DrawScope.axes(f: Frame, alpha: Float = 1f) {
    val c = Tone.Stone.copy(alpha = 0.55f * alpha)
    if (0.0 in f.ymin..f.ymax) drawLine(c, Offset(0f, f.sy(0.0)), Offset(size.width * alpha, f.sy(0.0)), 1.2f)
    if (0.0 in f.xmin..f.xmax) drawLine(c, Offset(f.sx(0.0), size.height), Offset(f.sx(0.0), size.height * (1 - alpha)), 1.2f)
}

private fun curvePath(p: MathEngine.Program, f: Frame, n: Int = 240): Path {
    // sample into polylines (breaking at gaps and asymptotes), then keep only the visible part so the pen's
    // time is spent where you can see it
    val lines = ArrayList<FloatArray>()
    val cur = ArrayList<Float>()
    var prev = Double.NaN
    val span = f.ymax - f.ymin
    fun flush() { if (cur.size >= 4) lines += cur.toFloatArray(); cur.clear() }
    for (i in 0..n) {
        val x = f.xmin + (f.xmax - f.xmin) * i / n
        val y = p.eval(x)
        if (!y.isFinite() || (prev.isFinite() && abs(y - prev) > span * 3)) { flush(); prev = y; continue }
        cur += x.toFloat(); cur += y.coerceIn(f.ymin - span * 50, f.ymax + span * 50).toFloat()
        prev = y
    }
    flush()
    return com.mathlens.app.ui.components.visiblePath(lines, { f.sx(it) }, { f.sy(it) }, f.h)
}

private fun DrawScope.drawPartial(path: Path, progress: Float, color: Color, width: Float) {
    if (progress <= 0f) return
    // walk every contour (curves with asymptotes have several) and reveal each proportionally
    val pm = android.graphics.PathMeasure(path.asAndroidPath(), false)
    val out = android.graphics.Path()
    var any = false
    do {
        val len = pm.length
        if (len > 0f) { pm.getSegment(0f, len * progress, out, true); any = true }
    } while (pm.nextContour())
    if (any) softStroke(out.asComposePath(), color, width)
}

private val shadowPaint = android.graphics.Paint(android.graphics.Paint.ANTI_ALIAS_FLAG).apply {
    style = android.graphics.Paint.Style.STROKE
    strokeCap = android.graphics.Paint.Cap.ROUND
    strokeJoin = android.graphics.Paint.Join.ROUND
}

/** A stroke lifted off the paper: blurred warm shadow below, crisp ink on top (2.5D). */
private fun DrawScope.softStroke(path: Path, color: Color, width: Float) {
    drawIntoCanvas { c ->
        shadowPaint.strokeWidth = width * 1.6f
        shadowPaint.color = android.graphics.Color.argb(46, 59, 42, 28)
        shadowPaint.maskFilter = android.graphics.BlurMaskFilter(width * 2.4f, android.graphics.BlurMaskFilter.Blur.NORMAL)
        c.nativeCanvas.save()
        c.nativeCanvas.translate(width * 1.1f, width * 2.2f)
        c.nativeCanvas.drawPath(path.asAndroidPath(), shadowPaint)
        c.nativeCanvas.restore()
    }
    drawPath(path, color, style = Stroke(width, cap = StrokeCap.Round))
}

private val dotShadow = android.graphics.Paint(android.graphics.Paint.ANTI_ALIAS_FLAG)

/** A paper disc with a contact shadow. */
private fun DrawScope.softDot(center: Offset, radius: Float, color: Color) {
    if (radius <= 0f) return
    drawIntoCanvas { c ->
        dotShadow.color = android.graphics.Color.argb(60, 59, 42, 28)
        dotShadow.maskFilter = android.graphics.BlurMaskFilter(radius * 0.9f, android.graphics.BlurMaskFilter.Blur.NORMAL)
        c.nativeCanvas.drawCircle(center.x + radius * 0.25f, center.y + radius * 0.5f, radius, dotShadow)
    }
    drawCircle(color, radius, center)
}

@Composable
private fun rememberPrograms(exprs: List<String>): List<MathEngine.Program?> {
    val progs = remember(exprs) { exprs.map { MathEngine.compile(it) } }
    DisposableEffect(progs) { onDispose { progs.forEach { it?.close() } } }
    return progs
}

/** Two caption lines are always reserved, so the drawing above never snaps when a caption wraps. */
val CaptionMinHeight = 56.dp

@Composable
private fun Caption(text: String, modifier: Modifier = Modifier) {
    AnimatedContent(text, transitionSpec = { fadeIn(tween(700, delayMillis = 550)) togetherWith fadeOut(tween(450)) }, label = "caption", modifier = modifier, contentAlignment = Alignment.Center) { t ->
        // every caption (including the first) fills the reserved band and centres itself in it
        Box(Modifier.fillMaxWidth().heightIn(min = CaptionMinHeight), contentAlignment = Alignment.Center) { CaptionText(t) }
    }
}

@Composable
