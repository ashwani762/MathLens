    Column(modifier.padding(horizontal = 18.dp, vertical = 16.dp)) {
        Box(Modifier.weight(1f).fillMaxWidth().clipToBounds()) { content() }
        Caption(caption, Modifier.padding(top = 10.dp).fillMaxWidth().heightIn(min = CaptionMinHeight).animateContentSize(tween(450)))
    }
}

// ------------------------------------------------------------------ curves meeting zero / each other

@Composable
private fun CurvesScene(plot: PlotSpec, kind: String, modifier: Modifier) {
    val explicit = plot.curves.filter { it.type == CurveType.Explicit }
    val progs = rememberPrograms(explicit.map { it.expr })
    val t = loopTime(9f)
    val hasTwo = explicit.size >= 2
    val caption = when {
        t < 2.4f -> if (hasTwo) "Each side of the equation is a curve" else "The equation drawn as a curve"
        t < 4.2f -> if (kind == "system") "Every point on a line solves its equation" else if (hasTwo) "They are equal where they cross" else "Solutions live where it meets zero"
        else -> if (plot.points.isEmpty()) "No real crossing, so no real solution" else if (plot.points.size == 1) "That single point is the answer" else "Each crossing is a solution"
    }
    SceneLayout(storyAt(if (t < 2.4f) 0 else if (t < 4.2f) 1 else 2, caption), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val f = frameFor(plot, size.width, size.height, equal = plot.curves.any { it.type != CurveType.Explicit })
            axes(f, phase(t, 0f, 0.8f))
            progs.forEachIndexed { i, p ->
                p ?: return@forEachIndexed
                drawPartial(curvePath(p, f), phase(t, 0.3f + i * 0.9f, 1.6f), if (i == 0) Tone.Ink else Tone.Terracotta, 3.2f)
            }
            // highlight y = 0 when there is a single curve
            if (!hasTwo && 0.0 in f.ymin..f.ymax) {
                val a = phase(t, 2.4f, 1f)
                drawLine(Tone.Terracotta.copy(alpha = 0.7f * a), Offset(0f, f.sy(0.0)), Offset(size.width * a, f.sy(0.0)), 2.2f,
                    pathEffect = PathEffect.dashPathEffect(floatArrayOf(10f, 10f)))
            }
            plot.points.forEachIndexed { i, pt ->
                val a = phase(t, 4.2f + i * 0.35f, 0.6f)
                if (a <= 0f || !pt.x.isFinite() || !pt.y.isFinite()) return@forEachIndexed
                val c = Offset(f.sx(pt.x), f.sy(pt.y))
                val drop = (1 - a) * -40f
                softDot(c.copy(y = c.y + drop), 9f * a, Tone.Terracotta)
                drawCircle(Tone.Ivory, radius = 3f * a, center = c.copy(y = c.y + drop))
            }
        }
        // labels for the points, placed so they never overlap each other, the dots, or the edges
        BoxWithConstraints(Modifier.fillMaxSize()) {
            val w = constraints.maxWidth.toFloat(); val h = constraints.maxHeight.toFloat()
            val f = frameFor(plot, w, h, equal = plot.curves.any { it.type != CurveType.Explicit })
            val density = androidx.compose.ui.platform.LocalDensity.current
            val spots = remember(plot, w, h) { placeLabels(plot.points, f, w, h, with(density) { 14.sp.toPx() }) }
            plot.points.forEachIndexed { i, pt ->
                val a = phase(t, 4.6f + i * 0.35f, 0.6f)
                if (!pt.x.isFinite() || !pt.y.isFinite()) return@forEachIndexed
                val spot = spots[i] ?: return@forEachIndexed
                Box(Modifier.offset { androidx.compose.ui.unit.IntOffset(spot.x.toInt(), spot.y.toInt()) }.graphicsLayer { alpha = a }.labelBg()) {
                    MathView(pt.label.ifEmpty { "(" + com.mathlens.app.ui.components.formatCoord(pt.x) + ", " + com.mathlens.app.ui.components.formatCoord(pt.y) + ")" }, fontSize = 14.sp, color = Tone.Ink)
                }
            }
        }
    }
}


/**
 * Greedy label placement: for each point try above, below, right and left of its dot; take the first
 * box that stays inside the canvas and clears every dot and every label placed so far, else skip it.
 * Label size is estimated from its visible characters (math is rendered at ~[fontPx]).
 */
private fun placeLabels(points: List<PlotPoint>, f: Frame, w: Float, h: Float, fontPx: Float): List<Offset?> {
    val dots = points.filter { it.x.isFinite() && it.y.isFinite() }.map { Offset(f.sx(it.x), f.sy(it.y)) }
    val boxes = ArrayList<androidx.compose.ui.geometry.Rect>()
    return points.map { pt ->
        if (!pt.x.isFinite() || !pt.y.isFinite()) return@map null
        val visible = pt.label.replace(Regex("\\\\(left|right|sqrt|frac|,|;|quad)"), "").replace(Regex("[{}\\\\ ]"), "").length.coerceAtLeast(5)
        val bw = visible * fontPx * 0.62f + fontPx; val bh = fontPx * 1.9f
        val c = Offset(f.sx(pt.x), f.sy(pt.y)); val g = fontPx * 0.7f
        val tries = listOf(Offset(c.x - bw / 2, c.y - g - bh), Offset(c.x - bw / 2, c.y + g), Offset(c.x + g, c.y - bh / 2), Offset(c.x - g - bw, c.y - bh / 2))
        tries.firstOrNull { o ->
            val r = androidx.compose.ui.geometry.Rect(o.x, o.y, o.x + bw, o.y + bh)
            r.left >= 0 && r.top >= 0 && r.right <= w && r.bottom <= h && boxes.none { it.overlaps(r) } && dots.none { d -> r.inflate(4f).contains(d) }
        }?.also { boxes += androidx.compose.ui.geometry.Rect(it.x, it.y, it.x + bw, it.y + bh) }
    }
}

// ------------------------------------------------------------------ derivative: sliding tangent

@Composable
private fun TangentScene(plot: PlotSpec, modifier: Modifier) {
    val progs = rememberPrograms(listOf(plot.curves[0].expr, plot.curves[1].expr))
    val t = loopTime(10f)
    val f = progs[0]; val df = progs[1]
    // position: sweep across the middle 70% of the view and back
    val u = if (t < 1.4f) 0f else ((t - 1.4f) / 8.6f)
    val sweep = (1 - kotlin.math.cos(u * 2 * Math.PI)).toFloat() / 2
    var readout = ""
    SceneLayout(storyAt(if (t < 1.4f) 0 else if (t < 7f) 1 else 2, "The derivative is the slope of the tangent"), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val fr = frameFor(plot, size.width, size.height)
            axes(fr, phase(t, 0f, 0.6f))
            f ?: return@Canvas
            drawPartial(curvePath(f, fr), phase(t, 0.2f, 1.2f), Tone.Ink, 3.2f)
            if (t < 1.4f || df == null) return@Canvas
            val x = fr.xmin + (fr.xmax - fr.xmin) * (0.15 + 0.7 * sweep)
            val y = f.eval(x)
            val m = df.eval(x)
            if (!y.isFinite() || !m.isFinite()) return@Canvas
            val p = Offset(fr.sx(x), fr.sy(y))
            // tangent segment of fixed on-screen length
            val pxPerX = size.width / (fr.xmax - fr.xmin)
            val pxPerY = size.height / (fr.ymax - fr.ymin)
            val ang = atan2(-m * pxPerY, pxPerX)
            val L = size.width * 0.22f
            val d = Offset((L * kotlin.math.cos(ang)).toFloat(), (L * kotlin.math.sin(ang)).toFloat())
            softStroke(Path().apply { moveTo((p - d).x, (p - d).y); lineTo((p + d).x, (p + d).y) }, Tone.Terracotta, 2.8f)
            // rise / run triangle
            val run = size.width * 0.09f
            val rise = (-m * pxPerY / pxPerX * run).toFloat()
            drawLine(Tone.Stone, p, p + Offset(run, 0f), 1.2f)
            drawLine(Tone.Stone, p + Offset(run, 0f), p + Offset(run, rise), 1.2f)
            softDot(p, 8f, Tone.Ink)
            drawCircle(Tone.Ivory, 2.6f, p)
            readout = "x = ${formatTick(x, 0.01)}    slope = ${formatTick(m, 0.01)}"
        }
        if (t >= 1.4f && f != null && df != null) {
            val x0 = plot.view[0] + (plot.view[1] - plot.view[0]) * (0.15 + 0.7 * sweep)
            val m = df.eval(x0)
            if (m.isFinite()) {
                Box(Modifier.align(Alignment.TopStart).padding(4.dp).labelBg()) {
                    MathView("f'(" + formatTick(x0, 0.01) + ") = " + formatTick(m, 0.01), fontSize = 17.sp, color = Tone.Terracotta)
                }
            }
        }
        @Suppress("UNUSED_EXPRESSION") readout
    }
}

// ------------------------------------------------------------------ integral: slices converge to the area

@Composable
private fun AreaScene(plot: PlotSpec, s: Solution, modifier: Modifier) {
    val progs = rememberPrograms(plot.curves.take(2).map { it.expr })
    val f = progs[0]
    val antiderivative = progs.getOrNull(1)
    val bounds = plot.shade
    val t = loopTime(11f)
    val levels = intArrayOf(2, 4, 8, 16, 48)
    val li = ((t - 1.4f) / 1.5f).toInt().coerceIn(0, levels.size - 1)
    val n = levels[li]
    val done = t > 1.4f + 1.5f * levels.size
    val caption = when {
        t < 1.4f -> if (bounds != null) "The area under the curve" else "An integral accumulates area"
        !done -> "Slice it into $n rectangles"
        else -> if (bounds != null) "Infinitely thin slices give the exact area" else "The antiderivative measures the area so far"
    }
    var approx = 0.0
    // indefinite integrals: sweep inside the widest continuous, on-screen stretch (never across an asymptote)
    val sweep = remember(plot, f) {
        val v = plot.view
        val x0 = v[0]; val x1 = v[1]; val ySpan = v[3] - v[2]
        val n = 600
        var best = Pair(x0 + (x1 - x0) * 0.2, x0 + (x1 - x0) * 0.75)
        if (f != null) {
            var runStart = -1; var bestLen = 0; var prev = Double.NaN
            for (i in 0..n) {
                val x = x0 + (x1 - x0) * i / n
                val y = f.eval(x)
                val ok = y.isFinite() && abs(y) < ySpan * 1.5 && !(prev.isFinite() && abs(y - prev) > ySpan * 0.5)
                if (ok && runStart < 0) runStart = i
                if ((!ok || i == n) && runStart >= 0) {
                    val end = if (ok) i else i - 1
                    if (end - runStart > bestLen) {
                        bestLen = end - runStart
                        val a = x0 + (x1 - x0) * runStart / n; val b = x0 + (x1 - x0) * end / n
                        best = Pair(a + (b - a) * 0.08, b - (b - a) * 0.04)
                    }
                    runStart = if (ok) i else -1
                }
                prev = y
            }
        }
        best
    }
    SceneLayout(storyAt(if (t < 1.4f) 0 else if (!done) 1 else 2, caption), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val fr = frameFor(plot, size.width, size.height)
            axes(fr, phase(t, 0f, 0.6f))
            f ?: return@Canvas
            val a = bounds?.first ?: sweep.first
            val b = bounds?.second ?: (sweep.first + (sweep.second - sweep.first) * (0.1 + 0.9 * phase(t, 1.4f, 7f)))
            if (t >= 1.4f && !done) {
                val w = (b - a) / n
                var sum = 0.0
                for (k in 0 until n) {
                    val xm = a + (k + 0.5) * w
                    val y = f.eval(xm)
                    if (!y.isFinite()) continue
                    sum += y * w
                    val top = fr.sy(max(y, 0.0)); val bot = fr.sy(min(y, 0.0))
                    val left = fr.sx(a + k * w); val right = fr.sx(a + (k + 1) * w)
                    drawRect(Tone.Terracotta.copy(alpha = 0.22f), Offset(left, top), Size(right - left, bot - top))
                    drawRect(Tone.Terracotta.copy(alpha = 0.7f), Offset(left, top), Size(right - left, bot - top), style = Stroke(1f))
                }
                approx = sum
            } else if (done) {
                val path = Path()
                path.moveTo(fr.sx(a), fr.sy(0.0))
                for (k in 0..160) {
                    val x = a + (b - a) * k / 160
                    val y = f.eval(x)
                    if (y.isFinite()) path.lineTo(fr.sx(x), fr.sy(y))
                }
                path.lineTo(fr.sx(b), fr.sy(0.0)); path.close()
                drawPath(path, Tone.Terracotta.copy(alpha = 0.3f * phase(t, 1.4f + 1.5f * levels.size, 0.8f)))
            }
            drawPartial(curvePath(f, fr), phase(t, 0.1f, 1.2f), Tone.Ink, 3.2f)
        }
        Box(Modifier.align(Alignment.TopStart).padding(4.dp).labelBg()) {
            if (done && bounds != null) {
                MathView(s.answers.firstOrNull()?.let { if (it.length < 40) "\\text{Area} = $it" else "\\text{Area}" } ?: "", fontSize = 17.sp, color = Tone.Terracotta)
            } else if (done && antiderivative != null) {
                // indefinite: area from a to the moving edge equals F(b) - F(a)
                val a = sweep.first
                val b = sweep.first + (sweep.second - sweep.first) * (0.1 + 0.9 * phase(t, 1.4f, 7f))
                val v = antiderivative.eval(b) - antiderivative.eval(a)
                if (v.isFinite()) MathView("F(" + formatTick(b, 0.01) + ") - F(" + formatTick(a, 0.01) + ") = " + formatTick(v, 0.001), fontSize = 16.sp, color = Tone.Terracotta)
            } else if (t >= 1.4f && approx != 0.0) {
                MathView("\\sum \\approx " + formatTick(approx, 0.0001), fontSize = 17.sp, color = Tone.Terracotta)
            }
        }
    }
}

