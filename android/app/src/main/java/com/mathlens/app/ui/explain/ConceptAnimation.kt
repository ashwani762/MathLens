    val featured = remember(plot) {
        plot.curves.indexOfFirst { Regex("C(_\\{?1\\}?)? = 0\\b").containsMatchIn(it.label) }.takeIf { it >= 0 } ?: (plot.curves.size / 2)
    }
    val active = if (t < allDrawn) ((t - 0.3f) / slot).toInt().coerceIn(0, n - 1) else featured
