// ------------------------------------------------------------------ linear equations on a balance

@Composable
private fun BalanceScene(steps: List<Triple<String, String, String>>, modifier: Modifier) {
    val per = 2.8f
    val t = loopTime(per * steps.size + 1.5f)
    val idx = (t / per).toInt().coerceIn(0, steps.size - 1)
    val local = t - idx * per
    // the beam dips when both sides change, then settles back to level
    val tilt = if (idx == 0) 0f else (7f * kotlin.math.exp(-3.2f * local) * kotlin.math.sin(local * 9f)).toFloat()
    val (title, lhs, rhs) = steps[idx]
    val caption = if (idx == 0) "An equation is a balance" else title.replace("$", "").ifEmpty { "Do the same to both sides" }
    SceneLayout(caption, modifier) {
        BoxWithConstraints(Modifier.fillMaxSize()) {
            val density = androidx.compose.ui.platform.LocalDensity.current
            val w = constraints.maxWidth.toFloat()
            val h = constraints.maxHeight.toFloat()
            // geometry shared by the drawing and the labels
            val pivot = Offset(w / 2, h * 0.16f)
            val half = w * 0.33f
            val drop = h * 0.36f           // string length
            val bowlW = w * 0.34f
            val bowlH = h * 0.12f
            val rad = Math.toRadians(tilt.toDouble())
            fun end(sgn: Float) = Offset(pivot.x + sgn * half * kotlin.math.cos(rad).toFloat(), pivot.y + sgn * half * kotlin.math.sin(rad).toFloat())
            Canvas(Modifier.fillMaxSize()) {
                // stand
                drawLine(Tone.Ink, pivot, Offset(pivot.x, h * 0.95f), 3f)
                drawLine(Tone.Ink, Offset(pivot.x - w * 0.08f, h * 0.95f), Offset(pivot.x + w * 0.08f, h * 0.95f), 3f, cap = StrokeCap.Round)
                val tri = Path().apply { moveTo(pivot.x, pivot.y - 12f); lineTo(pivot.x - 14f, pivot.y + 10f); lineTo(pivot.x + 14f, pivot.y + 10f); close() }
                drawPath(tri, Tone.Terracotta)
                // beam
                softStroke(Path().apply { moveTo(end(-1f).x, end(-1f).y); lineTo(end(1f).x, end(1f).y) }, Tone.Ink, 3f)
                // pans hang straight down from each end (gravity keeps them level)
                for (sgn in listOf(-1f, 1f)) {
                    val e = end(sgn)
                    val bowlTop = e.y + drop
                    drawLine(Tone.Stone, e, Offset(e.x - bowlW / 2, bowlTop), 1f)
                    drawLine(Tone.Stone, e, Offset(e.x + bowlW / 2, bowlTop), 1f)
                    drawArc(Tone.Ink, 0f, 180f, false, topLeft = Offset(e.x - bowlW / 2, bowlTop - bowlH / 2), size = Size(bowlW, bowlH), style = Stroke(2.2f))
                }
            }
            // each side of the equation sits on its own pan, centred and shrunk to fit
            for ((sgn, text) in listOf(-1f to lhs, 1f to rhs)) {
                val e = end(sgn)
                val labelW = bowlW * 1.05f
                val labelH = h * 0.14f
                Box(
                    Modifier
                        .offset { androidx.compose.ui.unit.IntOffset((e.x - labelW / 2).toInt(), (e.y + drop - labelH - 4).toInt()) }
                        .size(with(density) { labelW.toDp() }, with(density) { labelH.toDp() }),
                    contentAlignment = Alignment.BottomCenter,
                ) {
                    AnimatedContent(text, transitionSpec = { fadeIn(tween(400, delayMillis = 150)) togetherWith fadeOut(tween(200)) }, label = "side") {
                        MathView(it, Modifier.fillMaxSize(), fontSize = 20.sp, color = Tone.Ink, fit = MathFit.Shrink, center = true)
                    }
                }
            }
        }
    }
}

