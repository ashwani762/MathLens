/**
 * "Explain" visualisations: short looping animations built from the user's actual problem.
 * They favour a single idea per scene, drawn in ink on paper with one pigment accent.
 */
/** Captions generated by the engine from this solution; scenes use them per phase. */
val LocalStory = androidx.compose.runtime.compositionLocalOf<List<String>> { emptyList() }

@Composable
fun storyAt(phase: Int, fallback: String): String = LocalStory.current.getOrNull(phase) ?: fallback

/** True when there is a meaningful, problem-specific visual for this solution. */
fun hasConcept(s: Solution): Boolean {
    val plot = s.plot
    val balance = s.methods.firstOrNull()?.steps.orEmpty().count { splitEquation(it.latex) != null } >= 2
    return (s.kind == "linear" && balance) ||
        (s.kind == "complex" && plot != null && plot.points.isNotEmpty()) ||
        (s.kind == "factorial" && Regex("(\\d+)!").find(s.input)?.groupValues?.get(1)?.toIntOrNull()?.let { it in 1..6 } == true) ||
        (s.kind == "arithmetic" && fractionOf(s.answer) != null) ||
        (s.kind == "statistics" && plot != null && plot.points.isNotEmpty()) ||
        (plot?.shape?.type == "matrix2") ||
        (plot != null && plot.curves.isNotEmpty())
}

@Composable
fun ConceptAnimation(s: Solution, modifier: Modifier = Modifier) {
    androidx.compose.runtime.CompositionLocalProvider(LocalStory provides s.story) { ConceptAnimationInner(s, modifier) }
}

@Composable
private fun ConceptAnimationInner(s: Solution, modifier: Modifier = Modifier) {
    val plot = s.plot
    val steps = s.methods.firstOrNull()?.steps.orEmpty()
    val balanceSteps = remember(s) { steps.mapNotNull { st -> splitEquation(st.latex)?.let { Triple(st.title, it.first, it.second) } } }
    when {
        plot != null && plot.curves.any { it.type == CurveType.Surface } -> SurfaceScene(plot, modifier)
        plot?.shape?.type == "matrix2" -> MatrixScene(plot.shape, modifier)
        plot?.shape != null -> ShapeScene(plot.shape, modifier)
        s.kind == "system" && plot != null && plot.curves.any { it.type == CurveType.Implicit } -> SystemCurvesScene(plot, modifier)
        plot != null && plot.curves.any { it.type == CurveType.Implicit || it.type == CurveType.Polar } -> TraceScene(plot, modifier)
        s.kind == "taylor" && plot != null && plot.curves.size >= 2 -> TaylorScene(plot, modifier)
        s.kind == "ode" && plot != null && plot.curves.size >= 2 -> FamilyScene(plot, modifier)
        s.kind == "statistics" && plot != null && plot.points.isNotEmpty() -> DotScene(plot, modifier)
        s.kind == "finance" && plot != null && plot.shade != null -> NormalScene(plot, s, modifier)
        s.kind == "finance" && plot != null && plot.curves.isNotEmpty() -> FinanceScene(plot, modifier)
        s.kind == "inequality" && plot != null && plot.curves.isNotEmpty() -> InequalityScene(plot, s, modifier)
        s.kind == "linear" && balanceSteps.size >= 2 -> BalanceScene(balanceSteps, modifier)
        s.kind == "derivative" && plot != null && plot.curves.size >= 2 -> TangentScene(plot, modifier)
        s.kind == "integral" && plot != null && plot.curves.isNotEmpty() -> AreaScene(plot, s, modifier)
        s.kind == "limit" && plot != null && plot.curves.isNotEmpty() && plot.points.isNotEmpty() -> LimitScene(plot, modifier)
        s.kind == "complex" && plot != null && plot.points.isNotEmpty() && plot.curves.isEmpty() -> ComplexScene(plot, modifier)
        s.kind == "factorial" -> FactorialScene(s, modifier)
        s.kind == "arithmetic" && fractionOf(s.answer) != null -> FractionScene(fractionOf(s.answer)!!, modifier)
        plot != null && plot.curves.isNotEmpty() -> CurvesScene(plot, s.kind, modifier)
        else -> Box(modifier) {
            PaperArt(Modifier.fillMaxSize(), seed = s.query.hashCode(), background = Tone.Ivory)
        }
    }
}

