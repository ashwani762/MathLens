                val drawn = phase(t, start(i), slot)
                if (drawn <= 0f) return@forEach
                // red while being drawn, fading to grey over 0.7 s; the featured curve returns to red at the end
                val fadeOut = 1f - phase(t, start(i) + slot, 0.7f)
                val back = if (i == featured) phase(t, allDrawn, 0.9f) else 0f
                val red = if (drawn < 1f) 1f else maxOf(fadeOut, back)
                val color = androidx.compose.ui.graphics.lerp(grey, Tone.Terracotta, red)
                drawPartial(curvePath(p, fr), drawn, color, 1.8f + 1.4f * red)
            }
        }
        AnimatedContent(plot.curves[active].label, transitionSpec = { fadeIn(tween(350)) togetherWith fadeOut(tween(250)) },
            label = "familyLabel", modifier = Modifier.align(Alignment.TopStart).padding(4.dp)) { l ->
            Box(Modifier.labelBg()) { MathView(l, fontSize = 17.sp, color = Tone.Terracotta) }
        }
    }
}


// ------------------------------------------------------------------ 2x2 matrix: the plane bends

/**
 * A 2x2 matrix as a motion of the plane: the grid and the unit square morph from I to A (columns are
 * where the square's sides land), the area scales by |det|, then the motion replays with the
 * eigenvectors, which stay on their dashed lines and only stretch by λ.
 */
@Composable
private fun MatrixScene(shape: PlotShape, modifier: Modifier) {
    val q = shape.params
    val a = q[0]; val b = q[1]; val c = q[2]; val d = q[3]; val det = q[4]
    val hasEig = q[5] > 0.5
    val eig = if (hasEig) listOf(Triple(q[6], q[7], q[8]), Triple(q[9], q[10], q[11])) else emptyList()
    val t = loopTime(9f)
    val morph1 = phase(t, 0.7f, 1.6f)
    val morph2 = phase(t, 4.6f, 1.6f)
    val stage = if (t < 2.6f) 0 else if (t < 4.4f) 1 else 2
    val s = if (stage < 2) morph1 else morph2
    // M(s) = (1 - s) I + s A
    fun mx(x: Double, y: Double) = Pair((1 - s + s * a) * x + s * b * y, s * c * x + (1 - s + s * d) * y)
    // frame: origin, the image of the square and the eigen arrows all visible, equal aspect
    val ext = remember(shape) {
        val xs = listOf(0.0, 1.0, a, b, a + b) + eig.flatMap { (l, vx, _) -> listOf(vx, l * vx) }
        val ys = listOf(0.0, 1.0, c, d, c + d) + eig.flatMap { (l, _, vy) -> listOf(vy, l * vy) }
        val r = maxOf(xs.maxOf { abs(it) }, ys.maxOf { abs(it) }, 1.5) * 1.25
        r
    }
    val readout = when (stage) {
        0 -> "A = \\begin{bmatrix} " + formatCoord(a) + " & " + formatCoord(b) + " \\\\ " + formatCoord(c) + " & " + formatCoord(d) + " \\end{bmatrix}"
        1 -> "\\det A = " + formatCoord(det)
        else -> if (hasEig) "\\lambda_1 = " + formatCoord(eig[0].first) + ",\\ \\lambda_2 = " + formatCoord(eig[1].first) else "\\text{no real } \\lambda"
    }
    SceneLayout(storyAt(stage, "A matrix moves the plane"), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val u = minOf(size.width, size.height) / (2 * ext).toFloat()
            val o = Offset(size.width / 2, size.height / 2)
            fun p(x: Double, y: Double) = Offset(o.x + (x * u).toFloat(), o.y - (y * u).toFloat())
            fun pm(x: Double, y: Double) = mx(x, y).let { p(it.first, it.second) }
            // fixed axes
            drawLine(Tone.Stone.copy(alpha = 0.5f), Offset(0f, o.y), Offset(size.width, o.y), 1.2f)
            drawLine(Tone.Stone.copy(alpha = 0.5f), Offset(o.x, 0f), Offset(o.x, size.height), 1.2f)
            // the moving grid
            val n = ext.toInt() + 2
            val grid = Tone.Ink.copy(alpha = 0.12f * phase(t, 0f, 0.6f))
            for (k in -n..n) {
                drawLine(grid, pm(k.toDouble(), -n.toDouble()), pm(k.toDouble(), n.toDouble()), 1.2f)
                drawLine(grid, pm(-n.toDouble(), k.toDouble()), pm(n.toDouble(), k.toDouble()), 1.2f)
            }
            // eigenvector lines (dashed) stay fixed while everything else moves
            if (stage == 2) eig.forEach { (_, vx, vy) ->
                val far = ext * 3
                drawLine(Tone.Sage.copy(alpha = 0.9f), p(-vx * far, -vy * far), p(vx * far, vy * far), 2f,
                    pathEffect = PathEffect.dashPathEffect(floatArrayOf(12f, 10f)))
            }
            // the unit square -> parallelogram
            val sq = Path().apply {
                val p0 = pm(0.0, 0.0); val p1 = pm(1.0, 0.0); val p2 = pm(1.0, 1.0); val p3 = pm(0.0, 1.0)
                moveTo(p0.x, p0.y); lineTo(p1.x, p1.y); lineTo(p2.x, p2.y); lineTo(p3.x, p3.y); close()
            }
            val areaGlow = if (stage == 1) 0.18f + 0.14f * phase(t, 2.6f, 0.8f) else 0.14f
            drawPath(sq, Tone.Terracotta.copy(alpha = areaGlow * phase(t, 0.1f, 0.5f)))
            drawPath(sq, Tone.Ink.copy(alpha = phase(t, 0.1f, 0.5f)), style = Stroke(2.2f, join = StrokeJoin.Round))
            // basis vectors: where i-hat and j-hat go (the columns of A)
            fun arrow(to: Offset, color: Color, w: Float) {
                drawLine(color, o, to, w, cap = StrokeCap.Round)
                val dir = (to - o).let { val l = it.getDistance(); if (l < 1f) return; it / l }
                val nrm = Offset(-dir.y, dir.x)
                val head = Path().apply { moveTo(to.x, to.y); lineTo((to - dir * 16f + nrm * 7f).x, (to - dir * 16f + nrm * 7f).y); lineTo((to - dir * 16f - nrm * 7f).x, (to - dir * 16f - nrm * 7f).y); close() }
                drawPath(head, color)
            }
            if (stage < 2) {
                arrow(pm(1.0, 0.0), Tone.Terracotta, 4f)
                arrow(pm(0.0, 1.0), Tone.Klein, 4f)
            } else eig.forEach { (l, vx, vy) ->
                // an eigenvector only scales: from v to λv along its own line
                val k = 1 - s + s * l
                arrow(p(vx * k, vy * k), Tone.Terracotta, 4f)
            }
        }
        Box(Modifier.align(Alignment.TopStart).padding(4.dp).labelBg()) {
            MathView(readout, fontSize = 16.sp, color = Tone.Terracotta)
        }
    }
}

// ------------------------------------------------------------------ statistics: stacked dots and the mean

@Composable
private fun DotScene(plot: PlotSpec, modifier: Modifier) {
    val t = loopTime(8f)
    val data = plot.points.filter { it.label.isEmpty() }
    val mean = plot.points.firstOrNull { it.label.isNotEmpty() }
    val caption = if (t < 3.5f) "Each value is a dot on the number line" else "The mean is the balance point"
    SceneLayout(storyAt(if (t < 3.5f) 0 else 1, caption), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val x0 = plot.view[0]; val x1 = plot.view[1]
            val base = size.height * 0.78f
            fun sx(x: Double) = ((x - x0) / (x1 - x0) * size.width).toFloat()
            drawLine(Tone.Stone, Offset(0f, base), Offset(size.width, base), 1.4f)
            val r = min(size.width / (data.size * 1.6f + 4), size.height / ((plot.view[3] + 2) * 2.6f).toFloat()).coerceAtMost(18f)
            data.forEachIndexed { i, p ->
                val a = phase(t, 0.2f + i * 0.18f, 0.5f)
                if (a <= 0f) return@forEachIndexed
                val y = base - r * (2.2f * p.y.toFloat() - 1f) - (1 - a) * 80f
                softDot(Offset(sx(p.x), y), r * a, Tone.Ink)
            }
            if (mean != null) {
                val a = phase(t, 3.5f, 1f)
                val mx = sx(mean.x)
                drawLine(Tone.Terracotta.copy(alpha = a), Offset(mx, base + 20f), Offset(mx, base - size.height * 0.6f), 2.4f)
                val tri = Path().apply { moveTo(mx, base + 4f); lineTo(mx - 16f, base + 30f); lineTo(mx + 16f, base + 30f); close() }
                drawPath(tri, Tone.Terracotta.copy(alpha = a))
            }
        }
        if (mean != null && t > 3.5f) Box(Modifier.align(Alignment.TopStart).padding(4.dp).labelBg()) {
            MathView("\\bar{x} = " + formatTick(mean.x, 0.001), fontSize = 17.sp, color = Tone.Terracotta)
        }
    }
}

