/** Soft paper backing so overlay labels stay readable when a curve passes underneath. */
fun Modifier.labelBg(): Modifier = this
    .background(Tone.Ivory.copy(alpha = 0.9f), androidx.compose.foundation.shape.RoundedCornerShape(4.dp))
    .padding(horizontal = 4.dp, vertical = 1.dp)

/** Serif-italic caption; inline $math$ is typeset. Centred, wraps cleanly, never overflows. */
@OptIn(androidx.compose.foundation.layout.ExperimentalLayoutApi::class)
@Composable
fun CaptionText(t: String) {
    val style = MaterialTheme.typography.titleLarge.copy(fontStyle = FontStyle.Italic, fontSize = 18.sp, lineHeight = 24.sp)
    if (!t.contains('$')) {
        Text(t, style = style, color = Tone.Graphite, textAlign = TextAlign.Center, modifier = Modifier.fillMaxWidth())
        return
    }
    val parts = remember(t) { t.split('$') }
    androidx.compose.foundation.layout.FlowRow(
        Modifier.fillMaxWidth(),
        horizontalArrangement = androidx.compose.foundation.layout.Arrangement.Center,
        verticalArrangement = androidx.compose.foundation.layout.Arrangement.Center,
    ) {
        parts.forEachIndexed { i, part ->
            if (i % 2 == 1) {
                MathView(part, Modifier.align(Alignment.CenterVertically).padding(horizontal = 3.dp), fontSize = 15.sp, color = Tone.Ink, fit = MathFit.Shrink)
            } else {
                part.split(' ').filter { it.isNotEmpty() }.forEach { w ->
                    Text("$w ", style = style, color = Tone.Graphite, modifier = Modifier.align(Alignment.CenterVertically))
                }
            }
        }
    }
}


// ------------------------------------------------------------------ normal distribution: shade the area

@Composable
private fun NormalScene(plot: PlotSpec, s: Solution, modifier: Modifier) {
    val progs = rememberPrograms(listOf(plot.curves[0].expr))
    val f = progs[0]
    val (a, b) = plot.shade!!
    val t = loopTime(8f)
    SceneLayout(storyAt(if (t < 2f) 0 else if (t < 5f) 1 else 2, "Area under the bell curve"), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val fr = frameFor(plot, size.width, size.height)
            axes(fr)
            f ?: return@Canvas
            val edge = a.coerceAtLeast(fr.xmin) + (b - a.coerceAtLeast(fr.xmin)) * phase(t, 2f, 3f)
            val path = Path().apply {
                moveTo(fr.sx(fr.xmin), fr.sy(0.0))
                var x = fr.xmin
                while (x <= edge) { lineTo(fr.sx(x), fr.sy(f.eval(x))); x += (fr.xmax - fr.xmin) / 200 }
                lineTo(fr.sx(edge), fr.sy(0.0)); close()
            }
            drawPath(path, Tone.Terracotta.copy(alpha = 0.3f))
            drawPartial(curvePath(f, fr), phase(t, 0f, 1.6f), Tone.Ink, 3f)
            if (t > 2f) drawLine(Tone.Terracotta, Offset(fr.sx(edge), fr.sy(0.0)), Offset(fr.sx(edge), fr.sy(f.eval(edge))), 2f)
        }
    }
}

// ------------------------------------------------------------------ inequality: shade where it holds

@Composable
private fun InequalityScene(plot: PlotSpec, s: Solution, modifier: Modifier) {
    val progs = rememberPrograms(plot.curves.filter { it.type == CurveType.Explicit }.map { it.expr })
    val t = loopTime(8f)
    // the solution set comes from the engine's interval answer; test signs numerically only to shade
    val op = listOf("<=", ">=", "<", ">").firstOrNull { s.query.contains(it) } ?: "<"
    SceneLayout(storyAt(if (t < 2.5f) 0 else if (t < 5f) 1 else 2, "Where the inequality holds"), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val fr = frameFor(plot, size.width, size.height)
            axes(fr)
            val diff: (Double) -> Double = { x ->
                val l = progs.getOrNull(0)?.eval(x) ?: Double.NaN
                val r = progs.getOrNull(1)?.eval(x) ?: 0.0
                l - r
            }
            progs.forEachIndexed { i, p -> p?.let { drawPartial(curvePath(it, fr), phase(t, i * 0.6f, 1.4f), if (i == 0) Tone.Ink else Tone.Terracotta, 2.8f) } }
            val shade = phase(t, 2.5f, 2f)
            if (shade > 0f) {
                val n = 300
                var runStart: Double? = null
                for (k in 0..n) {
                    val x = fr.xmin + (fr.xmax - fr.xmin) * k / n
                    val d = diff(x)
                    val ok = d.isFinite() && when (op) { "<" -> d < 0; "<=" -> d <= 1e-9; ">" -> d > 0; else -> d >= -1e-9 }
                    if (ok && runStart == null) runStart = x
                    if ((!ok || k == n) && runStart != null) {
                        val x1 = x
                        drawRect(Tone.Terracotta.copy(alpha = 0.16f * shade), Offset(fr.sx(runStart), 0f), Size(fr.sx(x1) - fr.sx(runStart), size.height))
                        drawLine(Tone.Terracotta.copy(alpha = shade), Offset(fr.sx(runStart), fr.sy(0.0)), Offset(fr.sx(x1), fr.sy(0.0)), 5f, cap = StrokeCap.Round)
                        runStart = null
                    }
                }
            }
        }
    }
}

// ------------------------------------------------------------------ systems with curves: draw all, then the crossings

@Composable
private fun SystemCurvesScene(plot: PlotSpec, modifier: Modifier) {
    val samplers = remember(plot) { plot.curves.map { com.mathlens.app.ui.components.CurveSampler(it) } }
    DisposableEffect(samplers) { onDispose { samplers.forEach { it.close() } } }
    // frame the solutions: their bounding box, padded, at least 8 units across (equal aspect below)
    // closed curves (circles, ellipses) are included whole; unbounded ones (lines) are ignored
    val view = remember(plot) {
        val v = plot.view
        val xs = ArrayList<Double>(); val ys = ArrayList<Double>()
        plot.points.filter { it.x.isFinite() && it.y.isFinite() }.forEach { xs += it.x; ys += it.y }
        samplers.forEach { sm ->
            val segs = sm.sample(v[0], v[1], v[2], v[3], 400, 400)
            if (segs.isEmpty()) return@forEach
            var x0 = Double.MAX_VALUE; var x1 = -Double.MAX_VALUE; var y0 = Double.MAX_VALUE; var y1 = -Double.MAX_VALUE
            segs.forEach { pl -> for (j in 0 until pl.size / 2) { val x = pl[2 * j].toDouble(); val y = pl[2 * j + 1].toDouble(); x0 = min(x0, x); x1 = max(x1, x); y0 = min(y0, y); y1 = max(y1, y) } }
            val mx = (v[1] - v[0]) * 0.03; val my = (v[3] - v[2]) * 0.03
            val bounded = x0 > v[0] + mx && x1 < v[1] - mx && y0 > v[2] + my && y1 < v[3] - my
            if (bounded) { xs += x0; xs += x1; ys += y0; ys += y1 }
        }
        if (xs.isEmpty()) v else {
            val cx = (xs.min() + xs.max()) / 2; val cy = (ys.min() + ys.max()) / 2
            val half = maxOf(4.0, (xs.max() - xs.min()) * 0.62, (ys.max() - ys.min()) * 0.62)
            doubleArrayOf(cx - half, cx + half, cy - half, cy + half)
        }
    }
    val spec = remember(plot, view) { plot.copy(view = view) }
    val n = samplers.size
    // each curve: a quick left-to-right pen, one after another; then the crossings drop in
    // scene seconds run TEMPO x slower than real time: a curve takes ~0.85 s on screen
    val draw = 0.45f; val gap = 0.12f
    fun start(i: Int) = 0.1f + i * (draw + gap)
    val curvesDone = start(n - 1) + draw
    val tPoints = curvesDone + 0.1f
    val t = loopTime(tPoints + 0.25f * plot.points.size + 3.4f)
    val colors = listOf(Tone.Ink, Tone.Terracotta, Tone.Klein, Tone.Sage)
    // captions: the curves (while drawing), "on all of them" as the crossings drop in, then the coordinates
    SceneLayout(storyAt(if (t < curvesDone) 0 else if (t < tPoints + 1.1f) 1 else 2, "Where the curves meet"), modifier) {
        Canvas(Modifier.fillMaxSize()) {
            val fr = frameFor(spec, size.width, size.height, equal = true)
            axes(fr)
            samplers.forEachIndexed { i, sm ->
                val lin = phase(t, start(i), draw)
                if (lin <= 0f) return@forEachIndexed
                val a = lin * lin * (3 - 2 * lin)  // smoothstep: the pen accelerates, then settles
                val lines = sm.sample(fr.xmin, fr.xmax, fr.ymin, fr.ymax, size.width.toInt(), size.height.toInt())
                val path = Path()
                lines.forEach { pl ->
                    path.moveTo(fr.sx(pl[0].toDouble()), fr.sy(pl[1].toDouble()))
                    var k = 2
                    while (k < pl.size) { path.lineTo(fr.sx(pl[k].toDouble()), fr.sy(pl[k + 1].toDouble())); k += 2 }
                }
                drawPath(partialPath(path, a), colors[i % colors.size], style = Stroke(3f, cap = StrokeCap.Round, join = StrokeJoin.Round))
            }
            plot.points.forEachIndexed { i, pt ->
                val a = phase(t, tPoints + i * 0.25f, 0.35f)
                if (a <= 0f || !pt.x.isFinite() || !pt.y.isFinite()) return@forEachIndexed
                val c = Offset(fr.sx(pt.x), fr.sy(pt.y) - (1 - a) * 40f)
                softDot(c, 9f * a, Tone.Terracotta)
                drawCircle(Tone.Ivory, radius = 3f * a, center = c)
            }
        }
        // coordinates of each crossing
        BoxWithConstraints(Modifier.fillMaxSize()) {
            val w = constraints.maxWidth.toFloat(); val h = constraints.maxHeight.toFloat()
            val fr = frameFor(spec, w, h, equal = true)
            plot.points.forEachIndexed { i, pt ->
                val a = phase(t, tPoints + 0.2f + i * 0.25f, 0.35f)
                if (!pt.x.isFinite() || !pt.y.isFinite()) return@forEachIndexed
                Box(Modifier.offset { androidx.compose.ui.unit.IntOffset(fr.sx(pt.x).toInt() + 18, fr.sy(pt.y).toInt() - 64) }.graphicsLayer { alpha = a }.labelBg()) {
                    MathView(pt.label.ifEmpty { "(" + com.mathlens.app.ui.components.formatCoord(pt.x) + ", " + com.mathlens.app.ui.components.formatCoord(pt.y) + ")" }, fontSize = 14.sp, color = Tone.Ink)
                }
            }
        }
    }
}
